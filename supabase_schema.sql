-- ระบบตรวจวัดความชื้นดินและรดน้ำถั่วลิสงอัตโนมัติด้วย IoT
-- ============================================================

-- 1. Table: sensor_data (ตารางข้อมูลความชื้น อุณหภูมิ ความชื้นอากาศ)
CREATE TABLE IF NOT EXISTS public.sensor_data (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMPTZ DEFAULT NOW() NOT NULL,
    soil INT4 NOT NULL,
    temperature FLOAT8,
    humidity FLOAT8,
    pump_status BOOLEAN DEFAULT FALSE
);

ALTER TABLE public.sensor_data ENABLE ROW LEVEL SECURITY;
CREATE POLICY "Allow public all access to sensor_data" ON public.sensor_data FOR ALL USING (true) WITH CHECK (true);

-- 2. Table: farmer_users (ตารางข้อมูลผู้ใช้งาน/เกษตรกร)
CREATE TABLE IF NOT EXISTS public.farmer_users (
    id TEXT PRIMARY KEY,
    created_at TIMESTAMPTZ DEFAULT NOW() NOT NULL,
    name VARCHAR(100) NOT NULL,
    email VARCHAR(100) UNIQUE NOT NULL,
    phone VARCHAR(20),
    password VARCHAR(100) DEFAULT 'password123',
    role VARCHAR(20) DEFAULT 'farmer',
    plot_name VARCHAR(100) DEFAULT 'แปลงปลูกถั่วลิสง A1',
    device_id VARCHAR(50) DEFAULT 'ESP32-SOIL-NODE-01',
    status VARCHAR(20) DEFAULT 'active'
);

ALTER TABLE public.farmer_users ENABLE ROW LEVEL SECURITY;
CREATE POLICY "Allow public all access to farmer_users" ON public.farmer_users FOR ALL USING (true) WITH CHECK (true);

