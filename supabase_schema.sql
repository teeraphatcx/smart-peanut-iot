-- 3. Table: system_settings (ตารางเกณฑ์ค่ากำหนดระบบ IoT เพื่อให้เว็บกับ ESP32 คุยกันสองทาง)
CREATE TABLE IF NOT EXISTS public.system_settings (
    id INT PRIMARY KEY DEFAULT 1,
    min_soil INT NOT NULL DEFAULT 50,
    target_soil INT NOT NULL DEFAULT 80,
    auto_mode BOOLEAN NOT NULL DEFAULT TRUE,
    max_duration INT NOT NULL DEFAULT 300,
    crop_type VARCHAR(100) DEFAULT 'ถั่วลิสง (Peanut)',
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

ALTER TABLE public.system_settings ENABLE ROW LEVEL SECURITY;
CREATE POLICY "Allow public all access to system_settings" ON public.system_settings FOR ALL USING (true) WITH CHECK (true);

